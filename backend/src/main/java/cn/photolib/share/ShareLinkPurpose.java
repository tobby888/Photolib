package cn.photolib.share;

/**
 * 一条分享链接是用来看的还是用来传的。
 *
 * <p>两种用途的能力互斥，不是叠加：上传链接拿不到相册列表、下载地址和被引接口，
 * 浏览链接拿不到上传票据。开一条链接的人要回答的是「我要把什么交出去」，
 * 而「既能看全部又能往里传」这种组合在活动现场恰恰是最不该发出去的那种。</p>
 */
public enum ShareLinkPurpose {
    /** 浏览项目相册（V41 起就有的那一种）。 */
    BROWSE,
    /** 向活动选题的相册上传图片。 */
    UPLOAD
}
