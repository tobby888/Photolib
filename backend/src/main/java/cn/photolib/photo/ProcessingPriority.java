package cn.photolib.photo;

/**
 * 图片处理池里的排队优先级。处理池仍然只有一个线程（见 {@code AGENTS.md} §2.4），
 * 这里只决定"下一个先做谁"，不提高总吞吐。
 *
 * <p>10·26 活动当天，一个 1,461 MB 的压缩包一次塞进 68 张照片，排队 9 分钟才清空；
 * 那段时间别人单独上传的一张照片要排在 60 多张后面。按优先级出队后，单张上传、
 * 上传链接的单张提交和图片编辑插到批量条目前面；同一优先级内仍按提交顺序。
 */
public enum ProcessingPriority {
    /** 有人在页面上等结果：单张上传、上传链接单张提交、图片编辑。 */
    INTERACTIVE,
    /** ZIP 批量上传的条目。 */
    BATCH
}
