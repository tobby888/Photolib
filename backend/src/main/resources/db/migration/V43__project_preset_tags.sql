--
-- 选题有预设标签时，往该选题（及其需求）上传的图片、以及在选题里给图片新增的标签，
-- 只能从这组标签里选；没有预设标签（NULL 或空数组）时不做限制。直接向图库上传不受影响。
--
-- 刻意用 VARCHAR 而不是 JSON：选题列表按标签关键字 LIKE 搜索，JSON 列在 MySQL 会被
-- 重新序列化、在 H2 里会被当成 JSON 字符串再包一层，两边的 LIKE 行为都不可靠。
-- 上限按 30 个 × 50 字、加上 JSON 引号和逗号估算。
